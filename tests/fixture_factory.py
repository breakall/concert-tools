"""Synthetic, redistributable concert bundles for end-to-end tests."""

from __future__ import annotations

import plistlib
import struct
import uuid
from pathlib import Path

TEST_LARGE_TEXT_CONTROL = "\x01IDENTITY:Large Text"
TEST_SMALL_TEXT_CONTROL = "\x01IDENTITY:Small Text"


def attributed_text(value: str) -> bytes:
    return plistlib.dumps(
        {"$archiver": "NSKeyedArchiver", "$objects": ["$null", "unused", value], "$top": {}},
        fmt=plistlib.FMT_BINARY,
        sort_keys=False,
    )


def rewrite_synthetic_text(blob: bytes, replacement: str, _work_dir: Path) -> bytes:
    archive = plistlib.loads(blob)
    archive["$objects"][2] = replacement
    return plistlib.dumps(archive, fmt=plistlib.FMT_BINARY, sort_keys=False)


def keyed_archive(objects: list) -> bytes:
    return plistlib.dumps(
        {"$archiver": "NSKeyedArchiver", "$version": 100000, "$objects": objects, "$top": {}},
        fmt=plistlib.FMT_BINARY,
        sort_keys=False,
    )


def ucua_block(archive: bytes) -> bytes:
    header = bytearray(56)
    header[:4] = b"UCuA"
    struct.pack_into("<I", header, 28, len(archive) + 36)
    struct.pack_into("<I", header, 52, len(archive))
    return bytes(header) + archive + bytes(16)


def ocua_container(*archives: bytes) -> bytes:
    header = bytearray(36)
    header[:4] = b"OCuA"
    struct.pack_into("<I", header, 28, 0)
    return bytes(header) + b"".join(ucua_block(archive) for archive in archives)


def mapping_archive(instance_ids: list[int]) -> bytes:
    return keyed_archive(["$null", *({"kGInstIDKey": value} for value in instance_ids)])


def layout_archive(key: str, note: str) -> bytes:
    return keyed_archive(
        [
            "$null",
            {"NSString": plistlib.UID(2), "NSAttributes": plistlib.UID(3)},
            key,
            {"NS.objects": [plistlib.UID(4)]},
            {"NSSize": 96.0},
            {"NSString": plistlib.UID(6), "NSAttributes": plistlib.UID(7)},
            note,
            {"NS.objects": [plistlib.UID(8)]},
            {"NSSize": 48.0},
        ]
    )


def channel_uuid_archive(channel_uuid: str) -> bytes:
    return keyed_archive(["$null", {"UUIDBytes": uuid.UUID(channel_uuid).bytes}])


class _ArchiveTable:
    def __init__(self) -> None:
        self.objects: list = ["$null"]

    def add(self, value) -> plistlib.UID:
        reference = plistlib.UID(len(self.objects))
        self.objects.append(value)
        return reference

    def dump(self, top_key: str, top_reference: plistlib.UID) -> bytes:
        return plistlib.dumps(
            {
                "$version": 100000,
                "$archiver": "NSKeyedArchiver",
                "$top": {top_key: top_reference},
                "$objects": self.objects,
            },
            fmt=plistlib.FMT_BINARY,
            sort_keys=False,
        )


def _array(table: _ArchiveTable, items: list[plistlib.UID]) -> plistlib.UID:
    array_class = table.add({"$classname": "NSMutableArray", "$classes": ["NSMutableArray", "NSArray"]})
    return table.add({"NS.objects": items, "$class": array_class})


def _dictionary(table: _ArchiveTable, entries: list[tuple[plistlib.UID, plistlib.UID]]) -> plistlib.UID:
    dictionary_class = table.add(
        {"$classname": "NSMutableDictionary", "$classes": ["NSMutableDictionary", "NSDictionary"]}
    )
    return table.add(
        {
            "NS.keys": [key for key, _value in entries],
            "NS.objects": [value for _key, value in entries],
            "$class": dictionary_class,
        }
    )


def component_mapping_archive(targets: list[int]) -> bytes:
    table = _ArchiveTable()
    mappings = [table.add({"kGInstIDKey": target}) for target in targets]
    root = _array(table, mappings)
    return table.dump("root", root)


def component_embedded_mapping(controls: list[str], targets: list[int]) -> bytes:
    table = _ArchiveTable()
    entries = []
    for index, _control in enumerate(controls):
        key = table.add(index)
        mappings = [table.add({"kGInstIDKey": target}) for target in targets]
        entries.append((key, _array(table, mappings)))
    root = _dictionary(table, entries)
    return table.dump("dictionary", root)


def _identity(table: _ArchiveTable, name: str) -> plistlib.UID:
    identity_class = table.add({"$classname": "ScreenControlIdentity", "$classes": ["NSObject"]})
    return table.add({"uuidString": table.add(name), "autogenerated": False, "$class": identity_class})


def component_metadata_archive(
    controls: list[str], channel_uuid: str, labels: list[str] | None = None
) -> bytes:
    table = _ArchiveTable()
    identity_entries = [
        (_identity(table, control), table.add(index)) for index, control in enumerate(controls)
    ]
    identity_lookup = _dictionary(table, identity_entries)
    contains = _dictionary(table, [])
    uuid_class = table.add({"$classname": "_WsChannelUUID", "$classes": ["NSObject"]})
    uuid_value = table.add({"UUIDBytes": uuid.UUID(channel_uuid).bytes, "$class": uuid_class})
    label_entries = [(_identity(table, label), table.add(f"label:{label}")) for label in (labels or [])]
    label_lookup = _dictionary(table, label_entries)
    fields = [
        (table.add("IdentityIndexLookup"), identity_lookup),
        (table.add("ContainsBasedOnMapping"), contains),
        (table.add("UUID"), uuid_value),
        (table.add("kLgControlLabelLookupKey"), label_lookup),
    ]
    root = _dictionary(table, fields)
    return table.dump("dictionary", root)


def component_uuid_metadata(channel_uuid: str) -> bytes:
    table = _ArchiveTable()
    uuid_class = table.add({"$classname": "_WsChannelUUID", "$classes": ["NSObject"]})
    uuid_value = table.add({"UUIDBytes": uuid.UUID(channel_uuid).bytes, "$class": uuid_class})
    root = _dictionary(table, [(table.add("UUID"), uuid_value)])
    return table.dump("dictionary", root)


def make_component_patch(
    path: Path,
    *,
    name: str,
    instance_ids: list[int],
    controls: list[str],
    ui: dict,
    labels: list[str],
) -> None:
    path.mkdir()
    channel_uuids = [str(uuid.uuid4()).upper() for _ in instance_ids]
    channels = []
    for index, (instance_id, channel_uuid) in enumerate(
        zip(instance_ids, channel_uuids, strict=True), start=1
    ):
        filename = f"Layer {index}.cst"
        channels.append(
            {
                "Channel_name": f"{name} Layer {index}",
                "Channel_instID": instance_id,
                "UUID": channel_uuid,
                "Filename": filename,
                "Custom_icon": 100 + index,
            }
        )
        if index == 1:
            setting = ocua_container(
                component_embedded_mapping(controls, instance_ids),
                component_metadata_archive(controls, channel_uuid, labels),
            )
        else:
            setting = ocua_container(
                component_embedded_mapping([], []), component_uuid_metadata(channel_uuid)
            )
        (path / filename).write_bytes(setting)

    mapping_store = {
        f"\x01IDENTITY:{control}": component_mapping_archive(instance_ids) for control in controls
    }
    data = {
        "channels": channels,
        "patch": {
            "iconID": 700,
            "selected": False,
            "patchPath": str(path),
            "engineNode": {
                "name": name,
                "imageNameForSetFolder": "icon_patchlist_set",
                "hasProgramChange": False,
                "parameterMappingMap": {"storeDict": mapping_store},
                "uiPluginDataDict": ui,
            },
        },
    }
    with (path / "data.plist").open("wb") as handle:
        plistlib.dump(data, handle, fmt=plistlib.FMT_BINARY, sort_keys=False)


def make_patch(path: Path, *, name: str, key: str, note: str, instance_ids: list[int]) -> None:
    path.mkdir()
    channel_uuids = [str(uuid.uuid4()).upper() for _ in instance_ids]
    channels = []
    for index, (instance_id, channel_uuid) in enumerate(
        zip(instance_ids, channel_uuids, strict=True), start=1
    ):
        filename = f"Layer {index}.cst"
        channels.append(
            {
                "Channel_name": f"Layer {index}",
                "Channel_instID": instance_id,
                "UUID": channel_uuid,
                "Filename": filename,
            }
        )
        if index == 1:
            setting = ocua_container(
                mapping_archive(instance_ids),
                layout_archive(key, note),
                channel_uuid_archive(channel_uuid),
            )
        else:
            setting = ocua_container(channel_uuid_archive(channel_uuid))
        (path / filename).write_bytes(setting)

    mapping_blob = mapping_archive(instance_ids)
    data = {
        "channels": channels,
        "patch": {
            "selected": False,
            "engineNode": {
                "name": name,
                "parameterMappingMap": {"storeDict": {"controls": mapping_blob}},
                "uiPluginDataDict": {
                    TEST_LARGE_TEXT_CONTROL: {"storeDict": {"text": attributed_text(key)}},
                    TEST_SMALL_TEXT_CONTROL: {"storeDict": {"text": attributed_text(note)}},
                },
            },
        },
    }
    with (path / "data.plist").open("wb") as handle:
        plistlib.dump(data, handle, fmt=plistlib.FMT_BINARY, sort_keys=False)


def make_concert(path: Path) -> Path:
    root = path / "Concert.patch"
    root.mkdir(parents=True)
    make_patch(root / "Template.patch", name="Template", key="D", note="Template note", instance_ids=[10, 20])
    make_patch(root / "Second.patch", name="Second", key="A", note="Second note", instance_ids=[30, 40])
    with (root / "data.plist").open("wb") as handle:
        plistlib.dump(
            {"nodes": ["Template.patch", "Second.patch"]},
            handle,
            fmt=plistlib.FMT_BINARY,
            sort_keys=False,
        )
    return path
